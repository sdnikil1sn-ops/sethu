"""Write backend/requirements.lock (and requirements-dev.lock): every dependency pinned with the SHA-256 of every
file PyPI publishes for that version, for `pip install --require-hashes`. Standard library only.

    docker run --rm --entrypoint pip <built backend image> freeze > freeze.txt      # the exact versions in use
    python scripts/lock_python.py freeze.txt [dev-versions.txt]

Only small JSON requests are made (no wheel downloads), retried, so it works on a poor network. To upgrade a
dependency: change backend/pyproject.toml, build the image (the build resolves), re-run these two commands, and
review the diff of the lock files (docs/RUNBOOK.md, "Pinned dependencies").
"""
import json
import sys
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ("# Generated by scripts/lock_python.py from the versions installed in the backend image; do not edit.\n"
          "# pip install --require-hashes -r {name}\n")


def hashes(name: str, version: str) -> list[str]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    for attempt in range(1, 9):
        try:
            with urllib.request.urlopen(url, timeout=30) as r:  # noqa: S310 - fixed https host
                files = json.loads(r.read())["urls"]
            return sorted({f["digests"]["sha256"] for f in files})
        except Exception as e:  # noqa: BLE001 - retried; a poor network
            print(f"  {name}=={version}: attempt {attempt} failed ({type(e).__name__})", file=sys.stderr)
            time.sleep(min(30, 2 ** attempt))
    raise SystemExit(f"could not read hashes for {name}=={version}")


def pins(path: str) -> list[tuple[str, str]]:
    out = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith(("#", "-e", "sethu-backend")) and "==" in line:
            name, version = line.split("==", 1)
            out.append((name, version))
    return sorted(out, key=lambda p: p[0].lower())


def write(name: str, entries: list[tuple[str, str]]) -> None:
    lines = [HEADER.format(name=name)]
    for pkg, version in entries:
        digests = hashes(pkg, version)
        lines.append(f"{pkg}=={version} \\\n" + " \\\n".join(f"    --hash=sha256:{d}" for d in digests) + "\n")
    (ROOT / "backend" / name).write_text("".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote backend/{name}: {len(entries)} packages")


def main(freeze: str, dev: str | None = None) -> None:
    runtime = pins(freeze)
    write("requirements.lock", runtime)
    if dev:
        names = {p[0].lower() for p in runtime}
        write("requirements-dev.lock", runtime + [p for p in pins(dev) if p[0].lower() not in names])


if __name__ == "__main__":
    main(*sys.argv[1:3])
